// Builds the avatar rig from the brand tool's Grok Bot faces.
//
// Each face SVG in public/bots/<shape>/<face>.svg is one evenodd path: the
// body outline plus the eyes cut out of it. Within a shape the body is
// identical in every expression and only the eye subpaths change, so this
// splits them: subpaths shared by all faces are the body, the rest are that
// face's eyes. No geometry is drawn or changed.
//
// Writes, per shape, public/rig/<shape>.svg with <symbol id="body"> and one
// <symbol id="eyes-<face>"> per expression (referenced with <use>, cached by
// the browser), and src/lib/rig-meta.ts with each shape's body box and eye
// center for the engine's transforms.
//
//   bun src/scripts/build-rig.ts        (from apps/grok-bot)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const SRC = path.join(ROOT, "public/bots");
const OUT = path.join(ROOT, "public/rig");
const META = path.join(ROOT, "src/lib/rig-meta.ts");

type Box = [number, number, number, number];

function subpaths(file: string): string[] {
  const d = fs.readFileSync(file, "utf8").match(/ d="([^"]*)"/)?.[1];
  if (!d) throw new Error(`no path in ${file}`);
  return (d.match(/M[^M]*/g) ?? []).map((s) => s.trim());
}

// Bounds from the absolute coordinates (the faces use only M, L, C, Z).
function box(paths: string[]): Box {
  const xs: number[] = [];
  const ys: number[] = [];
  for (const d of paths) {
    if (/[a-y]/.test(d.replace(/z/gi, "")))
      throw new Error("relative path commands aren't supported");
    const nums = d
      .replace(/[A-Za-z]/g, " ")
      .trim()
      .split(/[\s,]+/)
      .map(Number);
    for (let i = 0; i + 1 < nums.length; i += 2) {
      xs.push(nums[i]);
      ys.push(nums[i + 1]);
    }
  }
  return [
    Math.min(...xs),
    Math.min(...ys),
    Math.max(...xs),
    Math.max(...ys),
  ].map((n) => Math.round(n * 10) / 10) as Box;
}

const symbol = (id: string, paths: string[]) =>
  `<symbol id="${id}" viewBox="0 0 1024 1024"><path fill-rule="evenodd" d="${paths.join(" ")}"/></symbol>`;

fs.mkdirSync(OUT, { recursive: true });
const meta: Record<string, { body: Box; eyes: Box }> = {};
const bodies: Record<string, string[]> = {};

for (const shape of fs.readdirSync(SRC).sort()) {
  const faces = fs
    .readdirSync(path.join(SRC, shape))
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.replace(/\.svg$/, ""))
    .sort();
  const byFace = Object.fromEntries(
    faces.map((f) => [f, subpaths(path.join(SRC, shape, `${f}.svg`))]),
  );
  const body = byFace[faces[0]].filter((s) =>
    faces.every((f) => byFace[f].includes(s)),
  );
  const eyes = Object.fromEntries(
    faces.map((f) => [f, byFace[f].filter((s) => !body.includes(s))]),
  );
  for (const f of faces)
    if (eyes[f].length === 0) throw new Error(`${shape}/${f}: no eye subpaths`);

  const sprite = [
    `<svg xmlns="http://www.w3.org/2000/svg">`,
    `<!-- Generated by src/scripts/build-rig.ts from public/bots/${shape}; do not edit. -->`,
    symbol("body", body),
    ...faces.map((f) => symbol(`eyes-${f}`, eyes[f])),
    `</svg>`,
  ].join("\n");
  fs.writeFileSync(path.join(OUT, `${shape}.svg`), `${sprite}\n`);
  bodies[shape] = body;
  meta[shape] = {
    body: box(body),
    eyes: box(eyes.neutral ?? eyes[faces[0]]),
  };
  console.log(
    `${shape.padEnd(9)} body ${body.length} subpaths, ${faces.length} faces, ${(sprite.length / 1024).toFixed(1)} KB`,
  );
}

// The round bot facing front: its official faces are drawn in the
// three-quarter "hero" pose (eyes near the upper right), which leaves no room
// to look up or right. public/eyes-front holds the brand tool's grok-bot-eyes
// frames looking front; they're drawn to sit on this same body (their
// viewBox is the body's box in the 1024 artboard), so they pair with the
// blob body unchanged.
const FRONT = path.join(ROOT, "public/eyes-front");
if (fs.existsSync(FRONT) && bodies.blob) {
  const faces = fs
    .readdirSync(FRONT)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.replace(/\.svg$/, ""))
    .sort();
  const eyes = Object.fromEntries(
    faces.map((f) => [f, subpaths(path.join(FRONT, `${f}.svg`))]),
  );
  const sprite = [
    `<svg xmlns="http://www.w3.org/2000/svg">`,
    `<!-- Generated by src/scripts/build-rig.ts from public/bots/blob and public/eyes-front; do not edit. -->`,
    symbol("body", bodies.blob),
    ...faces.map((f) => symbol(`eyes-${f}`, eyes[f])),
    `</svg>`,
  ].join("\n");
  fs.writeFileSync(path.join(OUT, "blob-front.svg"), `${sprite}\n`);
  meta.blobFront = { body: box(bodies.blob), eyes: box(eyes.neutral) };
  console.log(`blob-front body 1 subpath, ${faces.length} front faces`);
}

// Written in Biome's format so regenerating never fails the CI format check.
const list = (b: Box) => `[${b.join(", ")}]`;
const entries = Object.entries(meta)
  .map(
    ([shape, m]) =>
      `  ${shape}: {\n    body: ${list(m.body)},\n    eyes: ${list(m.eyes)},\n  },`,
  )
  .join("\n");
fs.writeFileSync(
  META,
  `// Generated by src/scripts/build-rig.ts; do not edit.\n// Per shape: body bounds and neutral eye bounds, in the 1024 viewBox.\nexport const RIG_META = {\n${entries}\n} as const;\n`,
);
